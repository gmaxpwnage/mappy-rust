//! 6502 -> Rust code generation.
//!
//! Every PRG byte offset gets its own Rust function. A function decodes just
//! one instruction, performs its side effects through the machine handle, and
//! sets `machine.cpu.pc` to wherever execution continues. A function-pointer
//! table indexed by `pc & 0x3FFF` is the dispatch mechanism, which mirrors how
//! the 6502 fetches its next opcode — but as direct calls between compiled
//! Rust functions instead of a byte-code interpreter loop.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use mos6502::disasm::Instr;
use mos6502::{Kind, Mode, OPCODES};

use crate::analysis::{Analysis, PRG_SIZE};

pub struct CodeGen<'a> {
    a: &'a Analysis,
    symbols: &'a BTreeMap<u16, String>,
    out: String,
}

/// Generate the complete Rust module for the PRG image.
pub fn generate(a: &Analysis, symbols: &BTreeMap<u16, String>) -> String {
    let mut g = CodeGen { a, symbols, out: String::with_capacity(12 << 20) };
    g.header();
    g.functions();
    g.dispatch_table();
    g.footer();
    g.out
}

impl<'a> CodeGen<'a> {
    fn header(&mut self) {
        let _ = writeln!(
            self.out,
            "// @generated by `decompiler` from \"Mappy (Japan) (En).nes\" — do not edit.
//!
//! The 6502 program of Mappy, translated to Rust.
//!
//! One function per PRG byte offset; each executes a single 6502 instruction
//! against [`Machine`] and branches to the address that follows. Control flow
//! is therefore expressed as Rust calls: the `DISPATCH` table at the bottom is
//! indexed by the program counter, exactly like the CPU's own opcode fetch.

#![allow(clippy::all, unused)]
#![allow(clippy::too_many_arguments, clippy::needless_return)]

use mos6502::{{
    adc_val, asl_val, cmp_val, lsr_val, read_ptr_buggy, rol_val, ror_val, sbc_val, Bus, FLAG_B,
    FLAG_C, FLAG_D, FLAG_I, FLAG_N, FLAG_U, FLAG_V, FLAG_Z,
}};
use nes::Machine;

/// Physical PRG size (NROM-128: 16 KiB mirrored to 32 KiB).
pub const PRG_SIZE: usize = {PRG_SIZE:#X};

/// CPU base address of the PRG image.
pub const PRG_BASE: u16 = 0xC000;

/// Set the program counter, preserving which 16 KiB mirror we are running in.
#[inline(always)]
fn next_pc(m: &Machine, phys_next: u16) -> u16 {{
    (m.cpu.pc & 0xC000) | (phys_next & 0x3FFF)
}}
"
        );
    }

    fn footer(&mut self) {
        let mut count = 0usize;
        for ins in self.a.instrs.values() {
            count += 1;
            let _ = ins;
        }
        let _ = writeln!(
            self.out,
            "// Number of instructions in the decompiled image: {count}."
        );
    }

    fn dispatch_table(&mut self) {
        let _ = writeln!(
            self.out,
            "\n/// Instruction dispatch table, indexed by `pc & 0x3FFF`."
        );
        let _ = writeln!(self.out, "pub static DISPATCH: [fn(&mut Machine); PRG_SIZE] = [");
        for p in 0..PRG_SIZE {
            let _ = writeln!(self.out, "    {},", self.fn_name(p as u16));
        }
        let _ = writeln!(self.out, "];\n");

        let _ = writeln!(
            self.out,
            r#"/// Execute one instruction at the current program counter.
///
/// This is the equivalent of the 6502's opcode fetch: the low 14 bits of the
/// PC select the translated function, which performs the instruction and
/// leaves the PC at the next instruction's address.
#[inline]
pub fn dispatch(m: &mut Machine) {{
    let phys = (m.cpu.pc & 0x3FFF) as usize;
    if m.cpu.pc < 0x8000 {{
        // Executing out of RAM is not something Mappy does; fall back to the
        // reference interpreter so behaviour still matches.
        m.step_cpu_only();
        return;
    }}
    DISPATCH[phys](m);
}}
"#
        );
    }

    fn fn_name(&self, phys: u16) -> String {
        let addr = 0xC000 | (phys & 0x3FFF);
        match self.symbols.get(&addr) {
            Some(name) => format!("fn_{name}"),
            None => format!("f_{phys:04x}"),
        }
    }

    fn functions(&mut self) {
        for p in 0..PRG_SIZE as u16 {
            self.function(p);
        }
    }

    fn function(&mut self, phys: u16) {
        let addr = 0xC000 | phys;
        let name = self.fn_name(phys);
        let label = self.symbols.get(&addr).cloned();
        let is_code = self.a.is_code(addr);
        let ins = self.a.instrs.get(&addr).copied().unwrap_or_else(|| {
            // Decode on the fly for data regions (kept so every offset has a body).
            mos6502::disasm::decode(addr, &|a| self.a.read(a))
        });

        let text = ins.text(&|a| {
            self.symbols
                .get(&a)
                .map(|s| s.clone())
                .or_else(|| self.a.labels.contains_key(&a).then(|| format!("${a:04X}")))
        });
        let mut doc = format!("/// `${addr:04X}` — `{text}`");
        if let Some(l) = &label {
            let _ = write!(doc, " — {l}");
        }
        if !is_code {
            let _ = write!(doc, "\n///\n/// Unreferenced by the static analysis (data region).");
        }
        let _ = writeln!(self.out, "\n{doc}\n#[inline(never)]\npub fn {name}(m: &mut Machine) {{");

        let body = self.body(&ins, is_code);
        for line in body {
            let _ = writeln!(self.out, "    {line}");
        }
        let _ = writeln!(self.out, "}}");
    }

    // -----------------------------------------------------------------
    // Instruction bodies.
    // -----------------------------------------------------------------

    fn body(&self, ins: &Instr, _is_code: bool) -> Vec<String> {
        let mut out: Vec<String> = Vec::new();
        let op = OPCODES[ins.opcode as usize];
        let phys_next = (crate::analysis::phys(ins.addr).wrapping_add(ins.len)) & 0x3FFF;
        let next_pc = format!("next_pc(m, {phys_next:#06x})");
        let kind = op.kind;

        // Cycles are always the first thing we know.
        let cycles = op.cycles as u32;

        // Address computation for memory-operand modes.
        let mut addr_lines: Vec<String> = Vec::new();
        let mut addr_expr: Option<String> = None;
        let mut page_base: Option<String> = None;
        match op.mode {
            Mode::Zp => addr_expr = Some(format!("0x{:02X}u16", ins.operand)),
            Mode::Zpx => {
                addr_expr = Some(format!("0x{:02X}u8.wrapping_add(m.cpu.x) as u16", ins.operand))
            }
            Mode::Zpy => {
                addr_expr = Some(format!("0x{:02X}u8.wrapping_add(m.cpu.y) as u16", ins.operand))
            }
            Mode::Abs => addr_expr = Some(format!("0x{:04X}u16", ins.operand)),
            Mode::AbsX => {
                addr_lines.push(format!("let base = 0x{:04X}u16;", ins.operand));
                addr_expr = Some("base.wrapping_add(m.cpu.x as u16)".into());
                page_base = Some("base".into());
            }
            Mode::AbsY => {
                addr_lines.push(format!("let base = 0x{:04X}u16;", ins.operand));
                addr_expr = Some("base.wrapping_add(m.cpu.y as u16)".into());
                page_base = Some("base".into());
            }
            Mode::IndX => {
                addr_lines.push(format!("let z = 0x{:02X}u8.wrapping_add(m.cpu.x);", ins.operand));
                addr_lines.push(
                    "let a = (m.read_byte(z as u16) as u16) | ((m.read_byte(z.wrapping_add(1) as u16) as u16) << 8);"
                        .into(),
                );
            }
            Mode::IndY => {
                addr_lines.push(format!("let z = 0x{:02X}u8;", ins.operand));
                addr_lines
                    .push("let base = (m.read_byte(z as u16) as u16) | ((m.read_byte(z.wrapping_add(1) as u16) as u16) << 8);".into());
                addr_expr = Some("base.wrapping_add(m.cpu.y as u16)".into());
                page_base = Some("base".into());
            }
            _ => {}
        }

        // Only read instructions with a page-crossing timing penalty use the
        // dynamic cycle count; stores and RMWs have fixed timing.
        if !op.page_penalty {
            page_base = None;
        }

        // Modes with a memory operand compute cycles after resolving the
        // address (they may cross a page); every other mode has fixed cycles.
        let memory_mode = matches!(
            op.mode,
            Mode::Zp | Mode::Zpx | Mode::Zpy | Mode::Abs | Mode::AbsX | Mode::AbsY | Mode::IndX | Mode::IndY
        );

        out.extend(addr_lines);
        if !memory_mode {
            out.push(format!("m.cpu.add_cycles({cycles});"));
        }
        if let Some(e) = &addr_expr {
            // IndX already binds `a`.
            if op.mode != Mode::IndX {
                out.push(format!("let a: u16 = {e};"));
            }
            let cyc = match &page_base {
                Some(base) => format!(
                    "m.cpu.add_cycles({cycles} + if ((a ^ {base}) & 0xFF00) != 0 {{ 1 }} else {{ 0 }});"
                ),
                None => format!("m.cpu.add_cycles({cycles});"),
            };
            out.push(cyc);
        }

        // The operation itself.
        let mut sets_pc = true;
        match kind {
            // ---- implied -------------------------------------------------
            Kind::Clc => out.push("m.cpu.set_flag(FLAG_C, false);".into()),
            Kind::Sec => out.push("m.cpu.set_flag(FLAG_C, true);".into()),
            Kind::Cli => out.push("m.cpu.set_flag(FLAG_I, false);".into()),
            Kind::Sei => out.push("m.cpu.set_flag(FLAG_I, true);".into()),
            Kind::Clv => out.push("m.cpu.set_flag(FLAG_V, false);".into()),
            Kind::Cld => out.push("m.cpu.set_flag(FLAG_D, false);".into()),
            Kind::Sed => out.push("m.cpu.set_flag(FLAG_D, true);".into()),
            Kind::Dex => {
                out.push("m.cpu.x = m.cpu.x.wrapping_sub(1);".into());
                out.push("m.cpu.set_nz(m.cpu.x);".into());
            }
            Kind::Dey => {
                out.push("m.cpu.y = m.cpu.y.wrapping_sub(1);".into());
                out.push("m.cpu.set_nz(m.cpu.y);".into());
            }
            Kind::Inx => {
                out.push("m.cpu.x = m.cpu.x.wrapping_add(1);".into());
                out.push("m.cpu.set_nz(m.cpu.x);".into());
            }
            Kind::Iny => {
                out.push("m.cpu.y = m.cpu.y.wrapping_add(1);".into());
                out.push("m.cpu.set_nz(m.cpu.y);".into());
            }
            Kind::Tax => {
                out.push("m.cpu.x = m.cpu.a;".into());
                out.push("m.cpu.set_nz(m.cpu.x);".into());
            }
            Kind::Tay => {
                out.push("m.cpu.y = m.cpu.a;".into());
                out.push("m.cpu.set_nz(m.cpu.y);".into());
            }
            Kind::Txa => {
                out.push("m.cpu.a = m.cpu.x;".into());
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::Tya => {
                out.push("m.cpu.a = m.cpu.y;".into());
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::Tsx => {
                out.push("m.cpu.x = m.cpu.sp;".into());
                out.push("m.cpu.set_nz(m.cpu.x);".into());
            }
            Kind::Txs => out.push("m.cpu.sp = m.cpu.x;".into()),
            Kind::Pha => {
                out.push("let v = m.cpu.a;".into());
                out.push("m.push(v);".into());
            }
            Kind::Php => {
                out.push("let v = m.cpu.p | FLAG_B | FLAG_U;".into());
                out.push("m.push(v);".into());
            }
            Kind::Pla => {
                out.push("m.cpu.a = m.pop();".into());
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::Plp => out.push("m.cpu.p = (m.pop() & !FLAG_B) | FLAG_U;".into()),
            Kind::AslA => {
                out.push("let (r, c) = asl_val(m.cpu.a);".into());
                out.push("m.cpu.a = r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::LsrA => {
                out.push("let (r, c) = lsr_val(m.cpu.a);".into());
                out.push("m.cpu.a = r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::RolA => {
                out.push("let (r, c) = rol_val(m.cpu.a, m.cpu.flag(FLAG_C));".into());
                out.push("m.cpu.a = r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::RorA => {
                out.push("let (r, c) = ror_val(m.cpu.a, m.cpu.flag(FLAG_C));".into());
                out.push("m.cpu.a = r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            // ---- control flow --------------------------------------------
            Kind::Jmp => {
                sets_pc = false;
                match op.mode {
                    Mode::Abs => out.push(format!("m.cpu.pc = {};", self.target_label(ins.operand))),
                    Mode::Ind => out.push(format!(
                        "m.cpu.pc = read_ptr_buggy(m, 0x{:04X}u16);",
                        ins.operand
                    )),
                    _ => unreachable!(),
                }
            }
            Kind::Jsr => {
                sets_pc = false;
                let ret = format!("next_pc(m, {phys_next:#06x})");
                out.push(format!("let ret = {ret} - 1;"));
                out.push("m.push((ret >> 8) as u8);".into());
                out.push("m.push(ret as u8);".into());
                out.push(format!("m.cpu.pc = {};", self.target_label(ins.operand)));
            }
            Kind::Rts => {
                sets_pc = false;
                out.push("let lo = m.pop() as u16;".into());
                out.push("let hi = m.pop() as u16;".into());
                out.push("m.cpu.pc = ((hi << 8) | lo).wrapping_add(1);".into());
            }
            Kind::Rti => {
                sets_pc = false;
                out.push("m.cpu.p = (m.pop() & !FLAG_B) | FLAG_U;".into());
                out.push("let lo = m.pop() as u16;".into());
                out.push("let hi = m.pop() as u16;".into());
                out.push("m.cpu.pc = (hi << 8) | lo;".into());
            }
            Kind::Brk => {
                sets_pc = false;
                out.push(format!("m.cpu.pc = {} + 1;", next_pc));
                out.push("let pc = m.cpu.pc;".into());
                out.push("m.push((pc >> 8) as u8);".into());
                out.push("m.push(pc as u8);".into());
                out.push("let p = m.cpu.p | FLAG_B | FLAG_U;".into());
                out.push("m.push(p);".into());
                out.push("m.cpu.set_flag(FLAG_I, true);".into());
                out.push("m.cpu.pc = m.read_word(0xFFFE);".into());
            }
            Kind::Kil => {
                sets_pc = false;
                out.push("m.cpu.jammed = true; // JAM: the CPU locks up".into());
            }
            k if k.is_branch() => {
                sets_pc = false;
                let cond = match k {
                    Kind::Bcc => "!m.cpu.flag(FLAG_C)",
                    Kind::Bcs => "m.cpu.flag(FLAG_C)",
                    Kind::Beq => "m.cpu.flag(FLAG_Z)",
                    Kind::Bne => "!m.cpu.flag(FLAG_Z)",
                    Kind::Bmi => "m.cpu.flag(FLAG_N)",
                    Kind::Bpl => "!m.cpu.flag(FLAG_N)",
                    Kind::Bvc => "!m.cpu.flag(FLAG_V)",
                    Kind::Bvs => "m.cpu.flag(FLAG_V)",
                    _ => unreachable!(),
                };
                let off = ins.operand as u8 as i8;
                out.push(format!("if {cond} {{"));
                out.push("    m.cpu.add_cycles(1);".into());
                out.push("    // Branches are relative to the address after the operand.".into());
                out.push("    let from = m.cpu.pc.wrapping_add(2);".into());
                out.push(format!(
                    "    let to = from.wrapping_add(0x{:04X}u16); // {off:+}",
                    off as u16
                ));
                out.push("    if ((from ^ to) & 0xFF00) != 0 { m.cpu.add_cycles(1); }".into());
                out.push("    m.cpu.pc = to;".into());
                out.push("} else {".into());
                out.push(format!("    m.cpu.pc = {next_pc};"));
                out.push("}".into());
            }
            // ---- immediate -----------------------------------------------
            Kind::Lda if op.mode == Mode::Imm => {
                out.push(format!("m.cpu.a = 0x{:02X};", ins.operand));
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::Ldx if op.mode == Mode::Imm => {
                out.push(format!("m.cpu.x = 0x{:02X};", ins.operand));
                out.push("m.cpu.set_nz(m.cpu.x);".into());
            }
            Kind::Ldy if op.mode == Mode::Imm => {
                out.push(format!("m.cpu.y = 0x{:02X};", ins.operand));
                out.push("m.cpu.set_nz(m.cpu.y);".into());
            }
            Kind::Ora if op.mode == Mode::Imm => {
                out.push(format!("m.cpu.a |= 0x{:02X};", ins.operand));
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::And if op.mode == Mode::Imm => {
                out.push(format!("m.cpu.a &= 0x{:02X};", ins.operand));
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::Eor if op.mode == Mode::Imm => {
                out.push(format!("m.cpu.a ^= 0x{:02X};", ins.operand));
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::Adc if op.mode == Mode::Imm => {
                out.push(format!(
                    "let (r, c, v) = adc_val(m.cpu.a, 0x{:02X}, m.cpu.flag(FLAG_C));",
                    ins.operand
                ));
                out.push("m.cpu.a = r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_flag(FLAG_V, v);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Sbc if op.mode == Mode::Imm => {
                out.push(format!(
                    "let (r, c, v) = sbc_val(m.cpu.a, 0x{:02X}, m.cpu.flag(FLAG_C));",
                    ins.operand
                ));
                out.push("m.cpu.a = r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_flag(FLAG_V, v);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Cmp if op.mode == Mode::Imm => {
                out.push(format!("let (r, c) = cmp_val(m.cpu.a, 0x{:02X});", ins.operand));
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Cpx if op.mode == Mode::Imm => {
                out.push(format!("let (r, c) = cmp_val(m.cpu.x, 0x{:02X});", ins.operand));
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Cpy if op.mode == Mode::Imm => {
                out.push(format!("let (r, c) = cmp_val(m.cpu.y, 0x{:02X});", ins.operand));
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Anc => {
                out.push(format!("m.cpu.a &= 0x{:02X};", ins.operand));
                out.push("m.cpu.set_nz(m.cpu.a);".into());
                out.push("m.cpu.set_flag(FLAG_C, m.cpu.a & 0x80 != 0);".into());
            }
            Kind::Alr => {
                out.push(format!("m.cpu.a &= 0x{:02X};", ins.operand));
                out.push("let (r, c) = lsr_val(m.cpu.a);".into());
                out.push("m.cpu.a = r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Arr => {
                out.push(format!("m.cpu.a &= 0x{:02X};", ins.operand));
                out.push("let (r, c) = ror_val(m.cpu.a, m.cpu.flag(FLAG_C));".into());
                out.push("m.cpu.a = r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_flag(FLAG_V, ((r >> 6) ^ (r >> 5)) & 1 != 0);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Xaa => {
                out.push(format!("let v = (m.cpu.a | 0xEE) & 0x{:02X};", ins.operand));
                out.push("m.cpu.a = v;".into());
                out.push("m.cpu.x = v;".into());
                out.push("m.cpu.set_nz(v);".into());
            }
            Kind::Axs => {
                out.push(format!("let (r, c) = cmp_val(m.cpu.a & m.cpu.x, 0x{:02X});", ins.operand));
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.x = r;".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Lax if op.mode == Mode::Imm => {
                out.push(format!("let v = 0x{:02X};", ins.operand));
                out.push("m.cpu.a = v;".into());
                out.push("m.cpu.x = v;".into());
                out.push("m.cpu.set_nz(v);".into());
            }
            Kind::Nop if op.mode == Mode::Imm || op.mode == Mode::Impl => {}
            // ---- memory reads --------------------------------------------
            Kind::Lda => {
                out.push("let v = m.read_byte(a);".into());
                out.push("m.cpu.a = v;".into());
                out.push("m.cpu.set_nz(v);".into());
            }
            Kind::Ldx => {
                out.push("let v = m.read_byte(a);".into());
                out.push("m.cpu.x = v;".into());
                out.push("m.cpu.set_nz(v);".into());
            }
            Kind::Ldy => {
                out.push("let v = m.read_byte(a);".into());
                out.push("m.cpu.y = v;".into());
                out.push("m.cpu.set_nz(v);".into());
            }
            Kind::Lax => {
                out.push("let v = m.read_byte(a);".into());
                out.push("m.cpu.a = v;".into());
                out.push("m.cpu.x = v;".into());
                out.push("m.cpu.set_nz(v);".into());
            }
            Kind::Las => {
                out.push("let v = m.read_byte(a) & m.cpu.sp;".into());
                out.push("m.cpu.a = v;".into());
                out.push("m.cpu.x = v;".into());
                out.push("m.cpu.sp = v;".into());
                out.push("m.cpu.set_nz(v);".into());
            }
            Kind::Ora => {
                out.push("m.cpu.a |= m.read_byte(a);".into());
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::And => {
                out.push("m.cpu.a &= m.read_byte(a);".into());
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::Eor => {
                out.push("m.cpu.a ^= m.read_byte(a);".into());
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::Adc => {
                out.push("let (r, c, v) = adc_val(m.cpu.a, m.read_byte(a), m.cpu.flag(FLAG_C));".into());
                out.push("m.cpu.a = r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_flag(FLAG_V, v);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Sbc => {
                out.push("let (r, c, v) = sbc_val(m.cpu.a, m.read_byte(a), m.cpu.flag(FLAG_C));".into());
                out.push("m.cpu.a = r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_flag(FLAG_V, v);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Cmp => {
                out.push("let (r, c) = cmp_val(m.cpu.a, m.read_byte(a));".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Cpx => {
                out.push("let (r, c) = cmp_val(m.cpu.x, m.read_byte(a));".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Cpy => {
                out.push("let (r, c) = cmp_val(m.cpu.y, m.read_byte(a));".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Bit => {
                out.push("let v = m.read_byte(a);".into());
                out.push("m.cpu.set_flag(FLAG_Z, m.cpu.a & v == 0);".into());
                out.push("m.cpu.set_flag(FLAG_N, v & 0x80 != 0);".into());
                out.push("m.cpu.set_flag(FLAG_V, v & 0x40 != 0);".into());
            }
            Kind::Nop => {
                // Read-only NOP still performs the bus read (which can have
                // side effects on $2007 and friends).
                out.push("let _ = m.read_byte(a);".into());
            }
            // ---- memory writes -------------------------------------------
            Kind::Sta => out.push("m.write_byte(a, m.cpu.a);".into()),
            Kind::Stx => out.push("m.write_byte(a, m.cpu.x);".into()),
            Kind::Sty => out.push("m.write_byte(a, m.cpu.y);".into()),
            Kind::Sax => out.push("let v = m.cpu.a & m.cpu.x; m.write_byte(a, v);".into()),
            Kind::Ahx => out.push(
                "let v = m.cpu.a & m.cpu.x & ((a >> 8) as u8).wrapping_add(1); m.write_byte(a, v);"
                    .into(),
            ),
            Kind::Shy => out.push(
                "let v = m.cpu.y & ((a >> 8) as u8).wrapping_add(1); m.write_byte(a, v);".into(),
            ),
            Kind::Shx => out.push(
                "let v = m.cpu.x & ((a >> 8) as u8).wrapping_add(1); m.write_byte(a, v);".into(),
            ),
            Kind::Tas => {
                out.push("m.cpu.sp = m.cpu.a & m.cpu.x;".into());
                out.push("let v = m.cpu.sp & ((a >> 8) as u8).wrapping_add(1);".into());
                out.push("m.write_byte(a, v);".into());
            }
            // ---- read-modify-write ---------------------------------------
            Kind::Asl => {
                out.push("let (r, c) = asl_val(m.read_byte(a));".into());
                out.push("m.write_byte(a, r);".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Lsr => {
                out.push("let (r, c) = lsr_val(m.read_byte(a));".into());
                out.push("m.write_byte(a, r);".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Rol => {
                out.push("let (r, c) = rol_val(m.read_byte(a), m.cpu.flag(FLAG_C));".into());
                out.push("m.write_byte(a, r);".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Ror => {
                out.push("let (r, c) = ror_val(m.read_byte(a), m.cpu.flag(FLAG_C));".into());
                out.push("m.write_byte(a, r);".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Inc => {
                out.push("let v = m.read_byte(a).wrapping_add(1);".into());
                out.push("m.write_byte(a, v);".into());
                out.push("m.cpu.set_nz(v);".into());
            }
            Kind::Dec => {
                out.push("let v = m.read_byte(a).wrapping_sub(1);".into());
                out.push("m.write_byte(a, v);".into());
                out.push("m.cpu.set_nz(v);".into());
            }
            Kind::Slo => {
                out.push("let (r, c) = asl_val(m.read_byte(a));".into());
                out.push("m.write_byte(a, r);".into());
                out.push("m.cpu.a |= r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::Rla => {
                out.push("let (r, c) = rol_val(m.read_byte(a), m.cpu.flag(FLAG_C));".into());
                out.push("m.write_byte(a, r);".into());
                out.push("m.cpu.a &= r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::Sre => {
                out.push("let (r, c) = lsr_val(m.read_byte(a));".into());
                out.push("m.write_byte(a, r);".into());
                out.push("m.cpu.a ^= r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(m.cpu.a);".into());
            }
            Kind::Rra => {
                out.push("let (r, c) = ror_val(m.read_byte(a), m.cpu.flag(FLAG_C));".into());
                out.push("m.write_byte(a, r);".into());
                out.push("let (res, c2, ovf) = adc_val(m.cpu.a, r, c);".into());
                out.push("m.cpu.a = res;".into());
                out.push("m.cpu.set_flag(FLAG_C, c2);".into());
                out.push("m.cpu.set_flag(FLAG_V, ovf);".into());
                out.push("m.cpu.set_nz(res);".into());
            }
            Kind::Dcp => {
                out.push("let v = m.read_byte(a).wrapping_sub(1);".into());
                out.push("m.write_byte(a, v);".into());
                out.push("let (r, c) = cmp_val(m.cpu.a, v);".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            Kind::Isc => {
                out.push("let v = m.read_byte(a).wrapping_add(1);".into());
                out.push("m.write_byte(a, v);".into());
                out.push("let (r, c, o) = sbc_val(m.cpu.a, v, m.cpu.flag(FLAG_C));".into());
                out.push("m.cpu.a = r;".into());
                out.push("m.cpu.set_flag(FLAG_C, c);".into());
                out.push("m.cpu.set_flag(FLAG_V, o);".into());
                out.push("m.cpu.set_nz(r);".into());
            }
            other => {
                out.push(format!("// TODO: unhandled operation {other:?} (mode {:?})", op.mode));
                out.push("unimplemented!();".into());
            }
        }

        if sets_pc {
            out.push(format!("m.cpu.pc = {next_pc};"));
        }
        out
    }

    fn target_label(&self, addr: u16) -> String {
        match self.symbols.get(&addr) {
            Some(name) => format!("0x{addr:04X}u16 /* {name} */"),
            None => format!("0x{addr:04X}u16"),
        }
    }
}
